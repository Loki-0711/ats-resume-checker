import React, { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { Sparkles, Check, ChevronDown, ChevronUp, Copy, CheckCheck } from 'lucide-react';
import type { AISuggestion, PriorityLevel } from '../types';

interface AISuggestionsProps {
  suggestions: AISuggestion[];
}

export const AISuggestions: React.FC<AISuggestionsProps> = ({ suggestions }) => {
  const [expandedId, setExpandedId] = useState<string | null>(suggestions[0]?.id || null);
  const [appliedIds, setAppliedIds] = useState<Record<string, boolean>>({});
  const [copiedId, setCopiedId] = useState<string | null>(null);

  const toggleExpand = (id: string) => {
    setExpandedId(expandedId === id ? null : id);
  };

  const handleApply = (id: string, e: React.MouseEvent) => {
    e.stopPropagation();
    setAppliedIds((prev) => ({ ...prev, [id]: !prev[id] }));
  };

  const handleCopy = (id: string, text: string, e: React.MouseEvent) => {
    e.stopPropagation();
    navigator.clipboard.writeText(text);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 2000);
  };

  const getPriorityBadge = (priority: PriorityLevel) => {
    switch (priority) {
      case 'high':
        return (
          <span className="px-2.5 py-0.5 rounded-full text-[10px] font-mono uppercase tracking-wider font-semibold bg-rose-500/15 border border-rose-500/30 text-rose-300">
            High Priority
          </span>
        );
      case 'medium':
        return (
          <span className="px-2.5 py-0.5 rounded-full text-[10px] font-mono uppercase tracking-wider font-semibold bg-amber-500/15 border border-amber-500/30 text-amber-300">
            Medium Priority
          </span>
        );
      default:
        return (
          <span className="px-2.5 py-0.5 rounded-full text-[10px] font-mono uppercase tracking-wider font-semibold bg-blue-500/15 border border-blue-500/30 text-blue-300">
            Low Priority
          </span>
        );
    }
  };

  return (
    <div className="glass-panel rounded-3xl p-6 sm:p-8 border-indigo-500/20 text-left">
      
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 mb-6">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <span className="w-2 h-2 rounded-full bg-cyan-400 animate-ping" />
            <span className="text-xs font-mono text-cyan-400 uppercase tracking-wider font-semibold">
              Algorithmic Guidance
            </span>
          </div>
          <h2 className="text-2xl font-bold text-white font-['Outfit']">
            AI Resume Recommendations
          </h2>
          <p className="text-xs sm:text-sm text-slate-400">
            Targeted revisions generated by our NLP engine to maximize your ATS pass rate and keyword prominence.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <span className="text-xs font-mono text-slate-400">
            {Object.keys(appliedIds).filter((k) => appliedIds[k]).length} of {suggestions.length} applied
          </span>
        </div>
      </div>

      {/* Suggestion Cards */}
      <div className="space-y-4">
        {suggestions.map((sug, idx) => {
          const isExpanded = expandedId === sug.id;
          const isApplied = !!appliedIds[sug.id];

          return (
            <motion.div
              key={sug.id}
              initial={{ opacity: 0, y: 15 }}
              whileInView={{ opacity: 1, y: 0 }}
              viewport={{ once: true }}
              transition={{ duration: 0.35, delay: idx * 0.08 }}
              className={`rounded-2xl border transition-all duration-300 overflow-hidden ${
                isApplied
                  ? 'bg-emerald-950/15 border-emerald-500/30'
                  : isExpanded
                  ? 'bg-slate-900/80 border-cyan-500/40 shadow-lg shadow-cyan-950/40'
                  : 'bg-slate-900/40 border-white/5 hover:border-white/15'
              }`}
            >
              {/* Card Header Row */}
              <div
                onClick={() => toggleExpand(sug.id)}
                className="p-4 sm:p-5 flex items-start justify-between gap-4 cursor-pointer select-none"
              >
                <div className="flex items-start gap-3.5">
                  <div className={`w-9 h-9 rounded-xl flex items-center justify-center shrink-0 mt-0.5 ${
                    isApplied 
                      ? 'bg-emerald-500 text-black' 
                      : 'bg-indigo-500/15 border border-indigo-500/30 text-indigo-400'
                  }`}>
                    {isApplied ? <Check className="w-5 h-5 stroke-[2.5]" /> : <Sparkles className="w-4 h-4" />}
                  </div>

                  <div>
                    <div className="flex flex-wrap items-center gap-2 mb-1">
                      <h4 className="text-base font-bold text-white font-['Outfit']">
                        {sug.title}
                      </h4>
                      {getPriorityBadge(sug.priority)}
                      <span className="text-[11px] font-mono px-2 py-0.5 rounded bg-emerald-500/10 text-emerald-400 border border-emerald-500/20">
                        {sug.impact}
                      </span>
                    </div>

                    <p className="text-xs text-slate-300 leading-relaxed max-w-2xl">
                      {sug.explanation}
                    </p>
                  </div>
                </div>

                {/* Right Action: Apply Button & Expand Chevron */}
                <div className="flex items-center gap-2 shrink-0">
                  <button
                    type="button"
                    onClick={(e) => handleApply(sug.id, e)}
                    className={`px-3 py-1.5 rounded-xl text-xs font-semibold flex items-center gap-1.5 transition-all ${
                      isApplied
                        ? 'bg-emerald-500/20 text-emerald-300 border border-emerald-500/40'
                        : 'bg-cyan-500/15 hover:bg-cyan-500/25 text-cyan-300 border border-cyan-500/30'
                    }`}
                  >
                    {isApplied ? (
                      <>
                        <Check className="w-3.5 h-3.5" />
                        <span>Applied</span>
                      </>
                    ) : (
                      <>
                        <span>Apply Suggestion</span>
                      </>
                    )}
                  </button>

                  <div className="p-1 rounded text-slate-400 hover:text-white">
                    {isExpanded ? <ChevronUp className="w-4 h-4" /> : <ChevronDown className="w-4 h-4" />}
                  </div>
                </div>
              </div>

              {/* Collapsible Before / After Example Box */}
              <AnimatePresence>
                {isExpanded && sug.exampleBefore && sug.exampleAfter && (
                  <motion.div
                    initial={{ height: 0, opacity: 0 }}
                    animate={{ height: 'auto', opacity: 1 }}
                    exit={{ height: 0, opacity: 0 }}
                    transition={{ duration: 0.25 }}
                    className="border-t border-white/5 bg-[#060a14] p-4 sm:p-5 text-xs font-mono space-y-3"
                  >
                    <div className="text-[11px] font-mono uppercase text-slate-400 tracking-wider flex items-center justify-between">
                      <span>Interactive Phrasing Transformation</span>
                      <button
                        type="button"
                        onClick={(e) => handleCopy(sug.id, sug.exampleAfter!, e)}
                        className="flex items-center gap-1 text-[11px] text-cyan-400 hover:text-cyan-300"
                      >
                        {copiedId === sug.id ? (
                          <>
                            <CheckCheck className="w-3.5 h-3.5 text-emerald-400" />
                            <span className="text-emerald-400">Copied</span>
                          </>
                        ) : (
                          <>
                            <Copy className="w-3.5 h-3.5" />
                            <span>Copy Rewrite</span>
                          </>
                        )}
                      </button>
                    </div>

                    <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
                      {/* Before Box */}
                      <div className="p-3 rounded-xl bg-rose-950/15 border border-rose-500/20">
                        <div className="text-[10px] text-rose-400 font-bold uppercase mb-1">
                          Original Phrasing (Weak Signal)
                        </div>
                        <div className="text-slate-300 leading-relaxed font-sans text-xs">
                          "{sug.exampleBefore}"
                        </div>
                      </div>

                      {/* After Box */}
                      <div className="p-3 rounded-xl bg-emerald-950/20 border border-emerald-500/30">
                        <div className="text-[10px] text-emerald-400 font-bold uppercase mb-1 flex items-center justify-between">
                          <span>Recommended AI Phrasing (ATS Optimized)</span>
                        </div>
                        <div className="text-slate-100 font-semibold leading-relaxed font-sans text-xs">
                          "{sug.exampleAfter}"
                        </div>
                      </div>
                    </div>
                  </motion.div>
                )}
              </AnimatePresence>
            </motion.div>
          );
        })}
      </div>

    </div>
  );
};
